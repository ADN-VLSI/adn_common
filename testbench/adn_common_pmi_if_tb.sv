`include "pmi/typedef.svh"

module adn_common_pmi_if_tb;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // IMPORTS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  // bring in the testbench essentials functions and macros
  `include "vip/adn_common_tb_headers.sv"

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // LOCALPARAMS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // TYPEDEFS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  `PMI_T(pmi, 16, 32)

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // SIGNALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  logic arst_n;
  logic clk;

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // VARIABLES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // INTERFACES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  adn_common_pmi_if #(
      .req_t(pmi_req_t),
      .rsp_t(pmi_rsp_t)
  ) vif (
      .arst_ni(arst_n),
      .clk_i  (clk)
  );

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // CLASSES
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // ASSIGNMENTS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // RTLS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // METHODS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //Task to Apply Reset
  task automatic apply_reset();
    #100ns;
    clk     <= '0;
    arst_n  <= '0;
    vif.rsp <= '0;
    #100ns;
    arst_n <= '1;
    #100ns;
  endtask

  task automatic start_clock();
    fork
      forever #5ns clk <= ~clk;
    join_none
    @(posedge clk);
  endtask

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // SEQUENTIALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  //////////////////////////////////////////////////////////////////////////////////////////////////
  // PROCEDURALS
  //////////////////////////////////////////////////////////////////////////////////////////////////

  initial begin  // main initial

    bit faltu;
    bit aro_faltu;

    apply_reset();
    start_clock();

    vif.rsp.mgnt <= '1;

    fork
      vif.mwrite('h1, 'h1, 'h1, faltu);  // 7
      vif.mwrite('h2, 'h2, 'h2, faltu);  // 8
      vif.mwrite('h3, 'h3, 'h3, faltu);  // 2
      vif.mwrite('h4, 'h4, 'h4, faltu);  // 6
      vif.mread('h5, faltu, aro_faltu);  // 1
      vif.mread('h6, faltu, aro_faltu);  // 5
      vif.mread('h7, faltu, aro_faltu);  // 3
      vif.mread('h8, faltu, aro_faltu);  // 4

      vif.ssend(0, 0);
      vif.ssend(0, 0);
      vif.ssend(0, 0);
      vif.ssend(0, 0);
      vif.ssend(0, 0);
      vif.ssend(0, 0);
      vif.ssend(0, 0);
      vif.ssend(0, 0);
    join

    $finish;

  end

  initial begin
    #1us;
    $fatal(1, "TIMEOUT");
  end

endmodule
